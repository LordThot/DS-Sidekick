var ctBuildingData = new Object();
function addData(building, level, wood, clay, stone, iron, time, 
                 dWood, dClay, dStone, dIron, dFood, ability_a, ability_b)
{
  if ( !ctBuildingData[building] )
  {
    ctBuildingData[building] = new Object();
    ctBuildingData[building].levels = new Array();
    for ( var i=0; i<=20; ++i )
    {
      ctBuildingData[building].levels[i] = new Object();
      ctBuildingData[building].levels[i].cost = new Object();
      ctBuildingData[building].levels[i].costs = new Array();
      ctBuildingData[building].levels[i].time = 0;
      ctBuildingData[building].levels[i].upkeep = new Object();
      ctBuildingData[building].levels[i].upkeeps = new Array();
      ctBuildingData[building].levels[i].upkeep.food = 0;
      ctBuildingData[building].levels[i].ability_a = 0;
      ctBuildingData[building].levels[i].ability_b = 0;
    }
  }
  ctBuildingData[building].levels[level].cost.wood = wood;
  ctBuildingData[building].levels[level].cost.clay = clay;
  ctBuildingData[building].levels[level].cost.stone = stone;
  ctBuildingData[building].levels[level].cost.iron = iron;
  ctBuildingData[building].levels[level].cost.total = wood+clay+stone+iron;
  ctBuildingData[building].levels[level].costs[0] = wood;
  ctBuildingData[building].levels[level].costs[1] = clay;
  ctBuildingData[building].levels[level].costs[2] = stone;
  ctBuildingData[building].levels[level].costs[3] = iron;
  ctBuildingData[building].levels[level].time = convertHMSToSec(time);
  ctBuildingData[building].levels[level].upkeep.wood = dWood;
  ctBuildingData[building].levels[level].upkeep.clay = dClay;
  ctBuildingData[building].levels[level].upkeep.stone = dStone;
  ctBuildingData[building].levels[level].upkeep.iron = dIron;
  ctBuildingData[building].levels[level].upkeep.food = dFood;
  ctBuildingData[building].levels[level].upkeeps[0] = dWood;
  ctBuildingData[building].levels[level].upkeeps[1] = dClay;
  ctBuildingData[building].levels[level].upkeeps[2] = dStone;
  ctBuildingData[building].levels[level].upkeeps[3] = dIron;
  ctBuildingData[building].levels[level].upkeeps[4] = dFood;

  if ( ability_a )
  {
    if ( !ability_a.indexOf || ability_a.indexOf(":") == -1 )
      ctBuildingData[building].levels[level].ability_a = ability_a;
    else
      ctBuildingData[building].levels[level].ability_a = convertHMSToSec(ability_a);
  }

  if ( ability_b )
  {
    if ( !ability_b.indexOf || ability_b.indexOf(":") == -1 )
      ctBuildingData[building].levels[level].ability_b = ability_b;
    else
      ctBuildingData[building].levels[level].ability_b = convertHMSToSec(ability_b);
  }
}
function convertHMSToSec(time)
{
  var parts = time.split(":");
  if ( parts.length==2 )
    return parts[0]*60+Number(parts[1]);
  else
    return parts[0]*3600+parts[1]*60+Number(parts[2]);
}

